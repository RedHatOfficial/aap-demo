#!/usr/bin/env bash
# Deploy Keycloak as a local OIDC provider for AAP and Automation Orchestrator.
# Dev/test only. No AAP or AO authentication configuration is changed.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KEYCLOAK_NAMESPACE="${KEYCLOAK_NAMESPACE:-aap-demo-keycloak}"
KEYCLOAK_IMAGE="${KEYCLOAK_IMAGE:-quay.io/keycloak/keycloak@sha256:79c623a22abacf3fe6c00a5fb30f5b7843d717b234033b80995891c06116d244}"
KEYCLOAK_REALM="${KEYCLOAK_REALM:-aap-lab}"
AAP_DEMO_STATE_ROOT="${AAP_DEMO_STATE_DIR:-${AAP_DEMO_DIR:-${XDG_STATE_HOME:-${HOME}/.local/state}/aap-demo}}"
STATE_DIR="${KEYCLOAK_STATE_DIR:-${AAP_DEMO_STATE_ROOT}/addons/keycloak}"
# Keep credentials created by the v1 addon usable when the v2 state directory
# has not been created yet. Once native state exists, it is authoritative.
if [ -z "${KEYCLOAK_STATE_DIR:-}" ] && [ ! -d "$STATE_DIR" ] && [ -d "${HOME}/.aap-demo/keycloak" ]; then
  STATE_DIR="${HOME}/.aap-demo/keycloak"
fi
ACTION="${1:-deploy}"

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "ERROR: required command not found: $1" >&2
    exit 1
  }
}

protected_namespace() {
  case "$1" in
    default | kube-* | openshift-* | aap-operator | automation-orchestrator)
      return 0
      ;;
    *)
      return 1
      ;;
  esac
}

require_cmd kubectl

if [ "$ACTION" = "--delete" ] || [ "$ACTION" = "delete" ]; then
  kubectl cluster-info >/dev/null 2>&1 || {
    echo "ERROR: kubectl is not connected to a cluster; refusing to remove Keycloak" >&2
    exit 1
  }
  if protected_namespace "$KEYCLOAK_NAMESPACE"; then
    echo "ERROR: refusing to delete protected namespace ${KEYCLOAK_NAMESPACE}" >&2
    exit 1
  fi
  _namespace_error="$(mktemp "${TMPDIR:-/tmp}/aap-demo-keycloak-delete.XXXXXX")"
  if ! kubectl get namespace "$KEYCLOAK_NAMESPACE" >/dev/null 2>"$_namespace_error"; then
    if grep -Eiq 'not found|notfound' "$_namespace_error"; then
      rm -f "$_namespace_error"
      echo "Keycloak namespace ${KEYCLOAK_NAMESPACE} does not exist"
      exit 0
    fi
    cat "$_namespace_error" >&2
    rm -f "$_namespace_error"
    echo "ERROR: unable to inspect Keycloak namespace ${KEYCLOAK_NAMESPACE}" >&2
    exit 1
  fi
  rm -f "$_namespace_error"
  _managed_by="$(kubectl get namespace "$KEYCLOAK_NAMESPACE" -o jsonpath='{.metadata.labels.app\.kubernetes\.io/managed-by}' 2>/dev/null || true)"
  _managed_part="$(kubectl get namespace "$KEYCLOAK_NAMESPACE" -o jsonpath='{.metadata.labels.app\.kubernetes\.io/part-of}' 2>/dev/null || true)"
  if [ "$_managed_by" != "aap-demo-keycloak" ] || [ "$_managed_part" != "aap-demo" ]; then
    echo "ERROR: refusing to delete unowned namespace ${KEYCLOAK_NAMESPACE}" >&2
    exit 1
  fi
  echo "Removing Keycloak namespace ${KEYCLOAK_NAMESPACE}..."
  kubectl delete namespace "$KEYCLOAK_NAMESPACE" --ignore-not-found
  echo "✓ Keycloak removed"
  echo "  Local credentials retained under: ${STATE_DIR}"
  exit 0
fi

for _cmd in curl jq openssl; do require_cmd "$_cmd"; done
kubectl cluster-info >/dev/null 2>&1 || {
  echo "ERROR: kubectl is not connected to a cluster" >&2
  exit 1
}
if protected_namespace "$KEYCLOAK_NAMESPACE"; then
  echo "ERROR: refusing to use protected namespace ${KEYCLOAK_NAMESPACE}" >&2
  exit 1
fi

mkdir -p "$STATE_DIR"
chmod 700 "$STATE_DIR"
umask 077

secret_file() {
  local _file="$STATE_DIR/$1"
  if [ ! -s "$_file" ]; then
    openssl rand -hex 24 | tr -d '\r\n' >"$_file"
  else
    local _normalized
    _normalized="$(mktemp "${TMPDIR:-/tmp}/aap-demo-secret.XXXXXX")"
    tr -d '\r\n' <"$_file" >"$_normalized"
    chmod 600 "$_normalized"
    mv "$_normalized" "$_file"
  fi
  chmod 600 "$_file"
  cat "$_file"
}

# Keep passwords generated by earlier addon versions while moving to filenames
# that identify the exact Keycloak user. The old AO label was especially
# misleading: that password belongs to aap-oidc-operator, not an AO account.
migrate_password_file() {
  local _legacy="$STATE_DIR/$1"
  local _current="$STATE_DIR/$2"
  if [ -e "$_legacy" ]; then
    if [ -e "$_current" ]; then
      echo "ERROR: both legacy and current Keycloak password files exist: ${_legacy}, ${_current}" >&2
      echo "  Resolve which password is active, then remove the obsolete file and retry." >&2
      exit 1
    fi
    mv "$_legacy" "$_current"
    chmod 600 "$_current"
  fi
}

migrate_password_file aap-user-password aap-oidc-admin-password
migrate_password_file ao-user-password aap-oidc-operator-password
migrate_password_file aap-auditor-password aap-oidc-auditor-password
migrate_password_file aap-developer-password aap-oidc-developer-password

secret_file admin-password >/dev/null
secret_file aap-client-secret >/dev/null
secret_file ao-client-secret >/dev/null
secret_file aap-oidc-admin-password >/dev/null
secret_file aap-oidc-operator-password >/dev/null
secret_file aap-oidc-auditor-password >/dev/null
secret_file aap-oidc-developer-password >/dev/null

cluster_domain="$(kubectl get route aap -n "${NAMESPACE:-aap-operator}" -o jsonpath='{.spec.host}' 2>/dev/null || true)"
if [ -n "$cluster_domain" ]; then
  cluster_domain="${cluster_domain#*.}"
else
  cluster_domain="apps.127.0.0.1.nip.io"
fi

KEYCLOAK_HOST="${KEYCLOAK_HOST:-keycloak.${cluster_domain}}"
AAP_HOST="$(kubectl get route aap -n "${NAMESPACE:-aap-operator}" -o jsonpath='{.spec.host}' 2>/dev/null || printf 'aap-aap-operator.%s' "$cluster_domain")"
AO_HOST="$(kubectl get route -n automation-orchestrator -o jsonpath='{.items[0].spec.host}' 2>/dev/null || printf 'automation-orchestrator.%s' "$cluster_domain")"
KEYCLOAK_INSECURE_TLS="${KEYCLOAK_INSECURE_TLS:-false}"
case "$KEYCLOAK_INSECURE_TLS" in
  true) CURL_TLS_ARGS=(-k) ;;
  false)
    KEYCLOAK_CA_FILE="${KEYCLOAK_CA_FILE:-}"
    if [ -z "$KEYCLOAK_CA_FILE" ]; then
      for _candidate_ca in \
        "${AAP_DEMO_STATE_ROOT}/certs/crc-ingress-ca.crt" \
        "${AAP_DEMO_CONFIG_DIR:-${HOME}/.aap-demo}/crc-ingress-ca.crt"; do
        if [ -s "$_candidate_ca" ]; then
          KEYCLOAK_CA_FILE="$_candidate_ca"
          break
        fi
      done
    fi
    CURL_TLS_ARGS=()
    [ -s "$KEYCLOAK_CA_FILE" ] && CURL_TLS_ARGS+=(--cacert "$KEYCLOAK_CA_FILE")
    ;;
  *)
    echo "ERROR: KEYCLOAK_INSECURE_TLS must be true or false" >&2
    exit 1
    ;;
esac
curl_local() { curl "${CURL_TLS_ARGS[@]}" "$@"; }
AAP_REDIRECT_OVERRIDE="${KEYCLOAK_AAP_REDIRECT_URI:-}"
KEYCLOAK_AAP_REDIRECT_URI="${KEYCLOAK_AAP_REDIRECT_URI:-https://${AAP_HOST}/}"
KEYCLOAK_AO_REDIRECT_URI="${KEYCLOAK_AO_REDIRECT_URI:-https://${AO_HOST}/api/v1/auth/oidc/callback}"
case "$KEYCLOAK_AAP_REDIRECT_URI:$KEYCLOAK_AO_REDIRECT_URI" in *\** | *\?* | *\#* | *@*)
  echo "ERROR: Keycloak redirect URIs must not contain wildcards, queries, fragments, or credentials" >&2
  exit 1
  ;;
esac
case "$KEYCLOAK_AAP_REDIRECT_URI:$KEYCLOAK_AO_REDIRECT_URI" in https://*/*:https://*/*) ;; *)
  echo "ERROR: Keycloak redirect URIs must be absolute HTTPS URLs" >&2
  exit 1
  ;;
esac
printf '%s' "$KEYCLOAK_AO_REDIRECT_URI" >"$STATE_DIR/ao-redirect-uri"
chmod 600 "$STATE_DIR/ao-redirect-uri"
printf '%s' "$AAP_REDIRECT_OVERRIDE" >"$STATE_DIR/aap-redirect-uri"
chmod 600 "$STATE_DIR/aap-redirect-uri"

realm_file="$(mktemp "${TMPDIR:-/tmp}/aap-lab-realm.XXXXXX.json")"
cleanup() { rm -f "$realm_file"; }
trap cleanup EXIT

jq -n \
  --arg realm "$KEYCLOAK_REALM" \
  --arg aap_host "$AAP_HOST" \
  --arg ao_host "$AO_HOST" \
  --arg aap_redirect_uri "$KEYCLOAK_AAP_REDIRECT_URI" \
  --arg ao_redirect_uri "$KEYCLOAK_AO_REDIRECT_URI" \
  --rawfile aap_secret_file "$STATE_DIR/aap-client-secret" \
  --rawfile ao_secret_file "$STATE_DIR/ao-client-secret" \
  --rawfile admin_password_file "$STATE_DIR/aap-oidc-admin-password" \
  --rawfile operator_password_file "$STATE_DIR/aap-oidc-operator-password" \
  --rawfile auditor_password_file "$STATE_DIR/aap-oidc-auditor-password" \
  --rawfile developer_password_file "$STATE_DIR/aap-oidc-developer-password" \
  '{
    realm: $realm,
    enabled: true,
    registrationAllowed: false,
    resetPasswordAllowed: true,
    clients: [
      {
        clientId: "aap-demo-aap",
        name: "AAP 2.6 OIDC test client",
        enabled: true,
        protocol: "openid-connect",
        publicClient: false,
        secret: ($aap_secret_file | rtrimstr("\n")),
        standardFlowEnabled: true,
        directAccessGrantsEnabled: false,
        defaultClientScopes: ["profile", "email", "roles", "web-origins", "acr", "groups"],
        protocolMappers: [{
          name: "aap-demo-aap audience",
          protocol: "openid-connect",
          protocolMapper: "oidc-audience-mapper",
          config: {"included.client.audience": "aap-demo-aap", "id.token.claim": "false", "access.token.claim": "true"}
        }, {
          name: "aap-demo-aap preferred username",
          protocol: "openid-connect",
          protocolMapper: "oidc-usermodel-property-mapper",
          config: {"user.attribute": "username", "claim.name": "preferred_username", "jsonType.label": "String", "id.token.claim": "true", "access.token.claim": "true", "userinfo.token.claim": "true"}
        }, {
          name: "aap-demo-aap email",
          protocol: "openid-connect",
          protocolMapper: "oidc-usermodel-property-mapper",
          config: {"user.attribute": "email", "claim.name": "email", "jsonType.label": "String", "id.token.claim": "true", "access.token.claim": "true", "userinfo.token.claim": "true"}
        }],
        redirectUris: [$aap_redirect_uri],
        webOrigins: ["https://" + $aap_host],
        attributes: {"post.logout.redirect.uris": $aap_redirect_uri}
      },
      {
        clientId: "aap-demo-ao",
        name: "Automation Orchestrator OIDC test client",
        enabled: true,
        protocol: "openid-connect",
        publicClient: false,
        secret: ($ao_secret_file | rtrimstr("\n")),
        standardFlowEnabled: true,
        directAccessGrantsEnabled: false,
        defaultClientScopes: ["profile", "email", "roles", "web-origins", "acr", "groups"],
        protocolMappers: [{
          name: "aap-demo-ao audience",
          protocol: "openid-connect",
          protocolMapper: "oidc-audience-mapper",
          config: {"included.client.audience": "aap-demo-ao", "id.token.claim": "false", "access.token.claim": "true"}
        }, {
          name: "aap-demo-ao preferred username",
          protocol: "openid-connect",
          protocolMapper: "oidc-usermodel-property-mapper",
          config: {"user.attribute": "username", "claim.name": "preferred_username", "jsonType.label": "String", "id.token.claim": "true", "access.token.claim": "true", "userinfo.token.claim": "true"}
        }, {
          name: "aap-demo-ao email",
          protocol: "openid-connect",
          protocolMapper: "oidc-usermodel-property-mapper",
          config: {"user.attribute": "email", "claim.name": "email", "jsonType.label": "String", "id.token.claim": "true", "access.token.claim": "true", "userinfo.token.claim": "true"}
        }],
        redirectUris: [$ao_redirect_uri],
        webOrigins: ["https://" + $ao_host],
        attributes: {"post.logout.redirect.uris": $ao_redirect_uri}
      }
    ],
    groups: [
      {name: "aap-admins"},
      {name: "aap-operators"},
      {name: "aap-auditors"},
      {name: "aap-developers"}
    ],
    users: [
      {
        username: "aap-oidc-admin",
        enabled: true,
        email: "aap-oidc-admin@example.test",
        emailVerified: true,
        firstName: "AAP OIDC",
        lastName: "Admin",
        groups: ["/aap-admins"],
        credentials: [{type: "password", value: ($admin_password_file | rtrimstr("\n")), temporary: false}]
      },
      {
        username: "aap-oidc-operator",
        enabled: true,
        email: "aap-oidc-operator@example.test",
        emailVerified: true,
        firstName: "AAP OIDC",
        lastName: "Operator",
        groups: ["/aap-operators"],
        credentials: [{type: "password", value: ($operator_password_file | rtrimstr("\n")), temporary: false}]
      },
      {
        username: "aap-oidc-auditor",
        enabled: true,
        email: "aap-oidc-auditor@example.test",
        emailVerified: true,
        firstName: "AAP OIDC",
        lastName: "Auditor",
        groups: ["/aap-auditors"],
        credentials: [{type: "password", value: ($auditor_password_file | rtrimstr("\n")), temporary: false}]
      },
      {
        username: "aap-oidc-developer",
        enabled: true,
        email: "aap-oidc-developer@example.test",
        emailVerified: true,
        firstName: "AAP OIDC",
        lastName: "Developer",
        groups: ["/aap-developers"],
        credentials: [{type: "password", value: ($developer_password_file | rtrimstr("\n")), temporary: false}]
      }
    ],
    clientScopes: [{
      name: "groups",
      protocol: "openid-connect",
      protocolMappers: [{
        name: "groups",
        protocol: "openid-connect",
        protocolMapper: "oidc-group-membership-mapper",
        config: {"full.path": "false", "id.token.claim": "true", "access.token.claim": "true", "userinfo.token.claim": "true", "claim.name": "groups"}
      }]
    }]
  }' >"$realm_file"

if kubectl get namespace "$KEYCLOAK_NAMESPACE" >/dev/null 2>&1; then
  _managed_by="$(kubectl get namespace "$KEYCLOAK_NAMESPACE" -o jsonpath='{.metadata.labels.app\.kubernetes\.io/managed-by}' 2>/dev/null || true)"
  _managed_part="$(kubectl get namespace "$KEYCLOAK_NAMESPACE" -o jsonpath='{.metadata.labels.app\.kubernetes\.io/part-of}' 2>/dev/null || true)"
  if [ "$_managed_by" != "aap-demo-keycloak" ] || [ "$_managed_part" != "aap-demo" ]; then
    echo "ERROR: refusing to use unowned namespace ${KEYCLOAK_NAMESPACE}" >&2
    exit 1
  fi
else
  kubectl create namespace "$KEYCLOAK_NAMESPACE" >/dev/null
  kubectl label namespace "$KEYCLOAK_NAMESPACE" \
    app.kubernetes.io/managed-by=aap-demo-keycloak \
    app.kubernetes.io/part-of=aap-demo --overwrite >/dev/null
fi
kubectl -n "$KEYCLOAK_NAMESPACE" create secret generic keycloak-admin \
  --from-file=password="$STATE_DIR/admin-password" --dry-run=client -o yaml | kubectl apply -f - >/dev/null
kubectl -n "$KEYCLOAK_NAMESPACE" create secret generic keycloak-realm \
  --from-file=aap-lab-realm.json="$realm_file" --dry-run=client -o yaml | kubectl apply -f - >/dev/null

if command -v sha256sum >/dev/null 2>&1; then
  realm_revision="$(sha256sum "$realm_file" | awk '{print $1}')"
  admin_revision="$(sha256sum "$STATE_DIR/admin-password" | awk '{print $1}')"
else
  realm_revision="$(shasum -a 256 "$realm_file" | awk '{print $1}')"
  admin_revision="$(shasum -a 256 "$STATE_DIR/admin-password" | awk '{print $1}')"
fi

sed \
  -e "s|__KEYCLOAK_IMAGE__|${KEYCLOAK_IMAGE}|g" \
  -e "s|__KEYCLOAK_HOST__|${KEYCLOAK_HOST}|g" \
  -e "s|__KEYCLOAK_REALM__|${KEYCLOAK_REALM}|g" \
  -e "s|__REALM_REVISION__|${realm_revision}|g" \
  -e "s|__ADMIN_REVISION__|${admin_revision}|g" \
  -e "s|aap-demo-keycloak|${KEYCLOAK_NAMESPACE}|g" \
  "$SCRIPT_DIR/keycloak.yaml" | kubectl apply -f - >/dev/null

echo "Waiting for Keycloak..."
kubectl rollout status deployment/keycloak -n "$KEYCLOAK_NAMESPACE" --timeout="${KEYCLOAK_ROLLOUT_TIMEOUT:-10m}"

# --import-realm only applies to a new realm. Reconcile the claims and user
# profile fields for realms created by an earlier version of this addon.
REQUEST_DIR="$(mktemp -d "${TMPDIR:-/tmp}/aap-demo-keycloak-migrate.XXXXXX")"
chmod 700 "$REQUEST_DIR"
cleanup_request_dir() { rm -rf "$REQUEST_DIR"; }
trap 'cleanup_request_dir; cleanup' EXIT

KC_TOKEN="$(curl_local -fsS -X POST "https://${KEYCLOAK_HOST}/realms/master/protocol/openid-connect/token" \
  -H 'Content-Type: application/x-www-form-urlencoded' \
  --data-urlencode 'client_id=admin-cli' \
  --data-urlencode 'grant_type=password' \
  --data-urlencode 'username=admin' \
  --data-urlencode "password@${STATE_DIR}/admin-password" | jq -r '.access_token // empty')"
[ -n "$KC_TOKEN" ] || {
  echo "ERROR: unable to authenticate to the Keycloak admin API for realm migration" >&2
  exit 1
}
KC_AUTH="$REQUEST_DIR/keycloak-admin-curl.conf"
printf 'header = "Authorization: Bearer %s"\n' "$KC_TOKEN" >"$KC_AUTH"

for client_id in aap-demo-aap aap-demo-ao; do
  desired_client="$(jq -c --arg client_id "$client_id" '.clients[] | select(.clientId==$client_id)' "$realm_file")"
  existing_client_id="$(curl_local -fsS "https://${KEYCLOAK_HOST}/admin/realms/${KEYCLOAK_REALM}/clients?clientId=${client_id}" --config "$KC_AUTH" | jq -r 'if length == 1 then .[0].id else empty end')"
  [ -n "$existing_client_id" ] || {
    echo "ERROR: Keycloak client ${client_id} was not found during realm migration" >&2
    exit 1
  }
  curl_local -fsS "https://${KEYCLOAK_HOST}/admin/realms/${KEYCLOAK_REALM}/clients/${existing_client_id}" --config "$KC_AUTH" \
    | jq --argjson desired "$desired_client" '.protocolMappers=$desired.protocolMappers' >"$REQUEST_DIR/${client_id}.json"
  curl_local -fsS -X PUT "https://${KEYCLOAK_HOST}/admin/realms/${KEYCLOAK_REALM}/clients/${existing_client_id}" \
    --config "$KC_AUTH" -H 'Content-Type: application/json' \
    --data-binary "@$REQUEST_DIR/${client_id}.json" >/dev/null
done

existing_users="$(curl_local -fsS "https://${KEYCLOAK_HOST}/admin/realms/${KEYCLOAK_REALM}/users?max=100" --config "$KC_AUTH")"
for username in aap-oidc-admin aap-oidc-operator aap-oidc-auditor aap-oidc-developer; do
  desired_user="$(jq -c --arg username "$username" '.users[] | select(.username==$username)' "$realm_file")"
  existing_user_id="$(printf '%s' "$existing_users" | jq -r --arg username "$username" '.[] | select(.username==$username) | .id' | head -n1)"
  [ -n "$existing_user_id" ] || {
    echo "ERROR: Keycloak user ${username} was not found during realm migration" >&2
    exit 1
  }
  existing_user="$(curl_local -fsS "https://${KEYCLOAK_HOST}/admin/realms/${KEYCLOAK_REALM}/users/${existing_user_id}" --config "$KC_AUTH")"
  printf '%s' "$existing_user" | jq --argjson desired "$desired_user" \
    '.firstName=$desired.firstName | .lastName=$desired.lastName | .email=$desired.email | .emailVerified=$desired.emailVerified | .enabled=$desired.enabled' \
    >"$REQUEST_DIR/${username}.json"
  curl_local -fsS -X PUT "https://${KEYCLOAK_HOST}/admin/realms/${KEYCLOAK_REALM}/users/${existing_user_id}" \
    --config "$KC_AUTH" -H 'Content-Type: application/json' \
    --data-binary "@$REQUEST_DIR/${username}.json" >/dev/null
done
echo "✓ Reconciled Keycloak realm claims and user profiles"

issuer="https://${KEYCLOAK_HOST}/realms/${KEYCLOAK_REALM}"
echo ""
echo "✓ Keycloak deployed"
echo "  Admin console: https://${KEYCLOAK_HOST}/admin/"
echo "  Issuer:        ${issuer}"
echo "  Realm:         ${KEYCLOAK_REALM}"
echo "  AAP client:    aap-demo-aap"
echo "  AO client:     aap-demo-ao"
if [ -n "$AAP_REDIRECT_OVERRIDE" ]; then
  echo "  AAP callback:  ${KEYCLOAK_AAP_REDIRECT_URI}"
else
  echo "  AAP callback:  Set by 'aap-demo keycloak configure --apply' from the Gateway authenticator slug"
fi
echo "  AO callback:   ${KEYCLOAK_AO_REDIRECT_URI}"
echo "  Credentials:   ${STATE_DIR}/"
echo ""
echo "  Run 'aap-demo keycloak configure --target all --apply' to wire AAP and AO."
echo "  Users and password files:"
echo "    aap-oidc-admin:     ${STATE_DIR}/aap-oidc-admin-password"
echo "    aap-oidc-operator:  ${STATE_DIR}/aap-oidc-operator-password"
echo "    aap-oidc-auditor:   ${STATE_DIR}/aap-oidc-auditor-password"
echo "    aap-oidc-developer: ${STATE_DIR}/aap-oidc-developer-password"
