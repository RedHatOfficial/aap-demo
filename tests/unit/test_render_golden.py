def test_storage_pvcs_match_bash_sed() -> None:
    """bash: ``sed -e s/__NAMESPACE__/…/g -e s/__AAP_NAME__/…/g``."""
    template = _package_text("aap_demo.data.manifests", "aap-storage-pvcs.yaml")
    rendered = list(
        yaml.safe_load_all(storage.render_pvcs(template, namespace=NAMESPACE, aap_name="aap"))
    )
    assert rendered == load_golden_all("aap-storage-pvcs.aap-operator.aap.yaml")


def test_storage_pvc_names_compose_the_aap_name() -> None:
    template = _package_text("aap_demo.data.manifests", "aap-storage-pvcs.yaml")
    docs = list(yaml.safe_load_all(storage.render_pvcs(template, namespace="ns", aap_name="myaap")))
    names = {doc["metadata"]["name"] for doc in docs}
    assert names == {"postgres-15-myaap-postgres-15-0", "myaap-hub-redis-data"}
    assert all(doc["spec"]["storageClassName"] == "nfs-local-rwx" for doc in docs)


