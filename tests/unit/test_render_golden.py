"""Golden-file tests for every rendered manifest (design §14 R6).

R6's instruction is explicit: switching from bash's ``awk``/``sed`` text
munging to real YAML manipulation is the right call, *and* the rendered output
must be pinned against what bash actually produces. The fixtures under
``tests/fixtures/golden/`` were generated by running bash's own pipelines
verbatim against ``config/`` — the exact commands are recorded next to each
fixture below.

Comparison is on the **parsed document**, not the text. Comments, key order
and blank lines differ by construction once a YAML round-trip replaces a
stream editor; what must not differ is the data the API server receives, and
that is what these assert.

One divergence is deliberate and has its own test:
:func:`test_subscription_channel_substitution_is_fixed`.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Dict

import pytest
import yaml

from aap_demo.cluster import aap as aap_mod
from aap_demo.cluster import olm, storage

GOLDEN = Path(__file__).resolve().parents[1] / "fixtures" / "golden"
NAMESPACE = "aap-operator"


def load_golden(name: str) -> Dict[str, Any]:
    return yaml.safe_load((GOLDEN / name).read_text(encoding="utf-8"))


def load_golden_all(name: str) -> Any:
    return list(yaml.safe_load_all((GOLDEN / name).read_text(encoding="utf-8")))


# ---------------------------------------------------------------------------
# OLM manifests
# ---------------------------------------------------------------------------


def test_catalogsource_matches_bash_sed() -> None:
    """bash: ``sed -e s|redhat-operator-index:v[0-9.]*|…v4.22| -e s|namespace: aap-operator|…|``."""
    rendered = yaml.safe_load(olm.render_catalogsource(NAMESPACE, "4.22"))
    assert rendered == load_golden("catalogsource.aap-operator.4.22.yaml")
    assert rendered["spec"]["image"].endswith("redhat-operator-index:v4.22")


def test_catalogsource_rewrites_only_the_index_tag() -> None:
    rendered = yaml.safe_load(olm.render_catalogsource("other-ns", "4.19"))
    assert rendered["spec"]["image"] == ("registry.redhat.io/redhat/redhat-operator-index:v4.19")
    assert rendered["metadata"]["namespace"] == "other-ns"
    assert rendered["spec"]["secrets"] == ["redhat-operators-pull-secret"]


def test_operatorgroup_matches_bash_sed() -> None:
    """bash: ``sed -e s|namespace: aap|…|g -e s|name: aap-og|…| -e s|- aap|…|``."""
    rendered = yaml.safe_load(olm.render_operatorgroup(NAMESPACE))
    assert rendered == load_golden("operatorgroup.aap-operator.yaml")
    assert rendered["metadata"]["name"] == "aap-operator-og"
    assert rendered["spec"]["targetNamespaces"] == [NAMESPACE]


def test_subscription_matches_bash_sed_at_the_default_channel() -> None:
    rendered = yaml.safe_load(olm.render_subscription(NAMESPACE, "stable-2.7"))
    assert rendered == load_golden("subscription.aap-operator.stable-2.7.yaml")


def test_subscription_leaves_source_namespace_alone() -> None:
    """bash's ``s|namespace: aap|…|`` has no ``g`` and is case-sensitive.

    ``sourceNamespace:`` therefore never matched, and it stays hardcoded to
    ``aap-operator``. Reproduced rather than fixed: R6 sanctions exactly one
    deliberate behavior change here (the channel), and quietly repointing the
    Subscription's source would be a second one.
    """
    rendered = yaml.safe_load(olm.render_subscription("custom-ns", "stable-2.7"))
    assert rendered["metadata"]["namespace"] == "custom-ns"
    assert rendered["spec"]["sourceNamespace"] == "aap-operator"


def test_subscription_channel_substitution_is_fixed() -> None:
    """R6's dead ``sed``: bash asked for 2.6 and silently installed 2.7.

    ``config/olm/subscription.yaml`` says ``channel: stable-2.7`` while the
    sed pattern still says ``channel: stable-2.6``, so the substitution has
    matched nothing since the 2.7 bump. The golden fixture records that:
    running bash's pipeline with ``AAP_CHANNEL=stable-2.6`` still emits
    ``stable-2.7``. The port sets ``spec.channel`` unconditionally.
    """
    bash_output = load_golden("subscription.aap-operator.stable-2.6.BUGGY.yaml")
    assert bash_output["spec"]["channel"] == "stable-2.7", (
        "fixture no longer demonstrates the bug — regenerate it from bash"
    )

    rendered = yaml.safe_load(olm.render_subscription(NAMESPACE, "stable-2.6"))
    assert rendered["spec"]["channel"] == "stable-2.6"
    # Everything *else* still matches what bash emitted.
    assert {k: v for k, v in rendered.items() if k != "spec"} == {
        k: v for k, v in bash_output.items() if k != "spec"
    }


