@pytest.mark.parametrize(
    "cr_name",
    ["minimal", "controller", "controller-eda", "minimal-rwx"],
)
def test_cr_matches_bash_awk(cr_name: str) -> None:
    """bash: ``awk '/storage_type: file/{print; print "    route_host: " host; next}…'``."""
    rendered = yaml.safe_load(aap_mod.render_cr(aap_mod.load_cr(cr_name), namespace=NAMESPACE))
    assert rendered == load_golden(f"cr.{cr_name}.{NAMESPACE}.yaml")


def test_controller_cr_gets_no_route_host() -> None:
    """The awk keys on ``storage_type: file``; the controller CR has no hub."""
    rendered = yaml.safe_load(aap_mod.render_cr(aap_mod.load_cr("controller"), namespace=NAMESPACE))
    assert rendered["spec"]["hub"] == {"disabled": True}
    assert "route_host" not in yaml.safe_dump(rendered)


def test_minimal_cr_route_host_lands_under_hub() -> None:
    rendered = yaml.safe_load(aap_mod.render_cr(aap_mod.load_cr("minimal"), namespace="other-ns"))
    assert rendered["spec"]["hub"]["route_host"] == ("aap-hub-other-ns.apps.127.0.0.1.nip.io")
    assert "route_host" not in rendered["spec"]


def test_noingress_cr_matches_bash_sed() -> None:
    rendered = yaml.safe_load(
        aap_mod.render_cr(
            aap_mod.load_cr("minimal-noingress"),
            namespace=NAMESPACE,
            public_url="https://aap.example.com",
            noingress=True,
        )
    )
    assert rendered == load_golden("cr.minimal-noingress.public.yaml")


def test_every_bundled_cr_is_renderable() -> None:
    """A CR added to the package data must not silently break the deploy path."""
    for name in aap_mod.available_crs():
        template = aap_mod.load_cr(name)
        if "noingress" in name:
            aap_mod.render_cr(template, namespace="ns", public_url="https://x", noingress=True)
        else:
            aap_mod.render_cr(template, namespace="ns")


def _package_text(package: str, name: str) -> str:
    from importlib.resources import files

    return files(package).joinpath(name).read_text(encoding="utf-8")
